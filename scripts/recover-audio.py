#!/usr/bin/env python3
"""Recover and verify native sound inputs; never executes firmware or opens USB."""
import hashlib,json,struct
from pathlib import Path
from midi_summary import summarize
from soundfont_summary import summarize as summarize_bank
from firmware_disassembly import disassemble_arm
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'nokia-ta1278-research/firmware/original/system-20261025T054301+0800'
u=(source/'user.bin').read_bytes();mmi=(source/'mmi.bin').read_bytes()
sha=lambda b:hashlib.sha256(b).hexdigest()
assert sha(u)=='8f0db2dc82f9e763cb700c2e5781b7ca7125a4d250f4c075dbec793eb549c1ca'
assert sha(mmi)=='14c573027f375ea6b5f8ead2c6c432f2773f373faaa3c8a33261d0de9737886c'
ui=ROOT/'nokia-ta1278-research/analysis/ui'
resources=[r for r in json.loads((ROOT/'nokia-ta1278-research/analysis/system/resource-index.json').read_text()) if r['kind']=='sound']
audio={r['source']:r for r in json.loads((ui/'audio-index.json').read_text())}
assert len(resources)==75
for r in resources:
    assert sha(mmi[r['offset']:r['offset']+r['size']])==r['sha256']
    if audio.get(r['file'],{}).get('file'): assert sha((ui/audio[r['file']]['file']).read_bytes())==r['sha256']
out=ROOT/'assets/audio';out.mkdir(exist_ok=True)
bank=u[0x7aa358:0xa21cc0]
assert sha(bank)=='9309119628275607526a94cf746f25a7ca5a6d688feeba9e7991b02008414ef0'
assert struct.unpack_from('<I',u,0xa51020)[0]==0x887aa358
bank_summary=summarize_bank(bank)
bank_summary.update({'source':'user.bin','source_sha256':sha(u),'offset':'0x7aa358','binding':'0x88a50ea4 -> 0x882b2c52 -> 0x88a5545e (RIFF/sfbk parser)'})
(out/'gm1_A21.sf2').write_bytes(bank)
(ROOT/'docs/evidence/native-soundfont.json').write_text(json.dumps(bank_summary,indent=2)+'\n')
entries=[]
def add(key,name,data,path,provenance,midi):
    row={'key':key,'name':name,'source':path,'bytes':len(data),'sha256':sha(data),'midi':midi,'evidence':provenance}
    if midi:row['smf']=summarize(data)
    entries.append(row)
for key,off,size,call in [('snake-food',0x2037f8,0x112,'0x8869079c..0x8869079e: event5 after score increment'),('snake-over',0x20390a,0x6d0,'0x88690c28..0x88690c2c: event6 during end handling')]:
    data=u[off:off+size];(out/(key+'.mid')).write_bytes(data)
    add(key,key,data,'assets/audio/'+key+'.mid',{'confidence':'code-verified','image':'user.bin','offset':hex(off),'size':size,'binding':call},True)
assert struct.unpack_from('<II',u,0x6908a8)==(0x8820390a,0x882037f8)
assert u[0x690566:0x69056a].hex()=='40f2d061'
assert u[0x690578:0x69057c].hex()=='40f21211'
def utf16(addr):
    off=addr-0x88000000;end=off
    while u[end:end+2]!=b'\0\0':end+=2
    return u[off:end].decode('utf-16le')
names=[utf16(struct.unpack_from('<I',u,0xc16550+i*4)[0]) for i in range(21)]
assert names[:2]==['Clock1','Clock 2'] and names[-3:]==['Calendar 2','Message 2','Message 3']
ids=[21,22,*range(2,21)]
for name,sid in zip(names,ids):
    r=next(r for r in resources if r['group']==0 and r['index']+1==sid)
    a=audio[r['file']];data=(ui/a['file']).read_bytes();smf=summarize(data)
    explicit=any((name=='Clock1' and 'Clock alert 1' in n)or(name=='Clock 2' and 'Clock alert 2' in n)or(name=='Message 2' and 'Message 2' in n) for t in smf['tracks']for n in t['names'])
    add(name,name,data,str((ui/a['file']).relative_to(ROOT)),{'confidence':'name-and-SMF-metadata' if explicit else 'order-based inference','sound_resource_id':hex(0x40000000+sid),'offset':r['offset_hex'],'name_pointer_table':'user.bin+0xc16550','note':'Names are verified UTF16 strings. Except named SMF titles, pairing to the sound index is inferred from the matching lists; native selector code is not fully traced.'},True)
r=next(r for r in resources if r['group']==0 and r['index']==23);a=audio[r['file']]
add('key','Key click',(ui/a['file']).read_bytes(),str((ui/a['file']).relative_to(ROOT)),{'confidence':'original asset; local event binding','sound_resource_id':'0x40000018','offset':r['offset_hex'],'note':'14 adjacent MP3 sound entries 0x18..0x25 are byte-identical short clicks, not distinct DTMF samples. Key-event association remains local policy.'},False)
rust=['// Generated by scripts/recover-audio.py; verify before changing bindings.','pub static SOUNDS: &[Sound] = &[']
for e in entries:
    rust.append('    Sound { key: '+json.dumps(e['key'])+', name: '+json.dumps(e['name'])+', midi: '+str(e['midi']).lower()+', bytes: include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../'+e['source']+'")) },')
rust+= ['];','pub const RINGTONES: &[&str] = &'+json.dumps(names)+';']
(out/'catalog.rs').write_text('\n'.join(rust)+'\n')
manifest={'user_sha256':sha(u),'mmi_sha256':sha(mmi),'verified_sres_sounds':75,'entries':entries,'soundfont':{'file':'assets/audio/gm1_A21.sf2','sha256':sha(bank),'offset':'user.bin+0x7aa358'},'rendering':'Original SMF events and original SF2 bank rendered by OxiSynth 0.1.0. The DSP, interpolation, effects, gain, polyphony and output timing are independent host implementation choices; identical handset waveforms are not established.'}
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
listing=disassemble_arm(u,0x88000000,[(0x8869054c,0x88690580),(0x88690794,0x886907a2),(0x88690c12,0x88690c38),(0x88a50e9e,0x88a50eac),(0x882b2c52,0x882b2c76),(0x88a5545e,0x88a554b0)])
(ROOT/'docs/evidence/native-audio-code.txt').write_text(listing)
print('Verified 75 original sounds; recovered two code-bound Snake SMFs, 21 named/inferred presets and one native click.')
